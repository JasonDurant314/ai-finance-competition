"""「表内连续年份序列 → 列期间」规则的测试（第十四轮）。

实测动机（卡了四轮的 capex）：601857 2025 年报 p7 的**五年摘要表**没有自己的
表头，年份印在脚注里：

    注：（1）截至 2021 年 12 月 31 日、2022 年 12 月 31 日、…… 2025 年 12 月 31 日

于是 ``资本性支出`` 行的 2025 / 2024 / 2023 三个值被**全部标成同一期间**，
三条候选的置信度、口径、单位完全相同，**没有任何信号能把它们分开** ——
R4 只能"分歧即不取"，capex 因此一直不是事实值。

规则：**N 个数据列 + 表内出现 N 个连续年份 → 按从新到旧分配。**
交叉验证来自 p7 表 0（表头明写 ``2025 年 | 2024 年 | 2023 年 …``，数据从新到旧）。
"""

from __future__ import annotations

from pipelines.r1_extract.table_facts import periods_from_year_sequence


def _p7_capex_grid() -> list[list[str]]:
    """p7 五年摘要表的实测结构（数据列 1..5，年份在脚注行）。"""
    return [
        ["资本性支出", "269,089", "275,849", "275,393", "274,494", "251,323", ""],
        ["经营活动产生的现金流量净额", "412,510", "406,532", "456,847", "393,246",
         "341,424", ""],
        ["注：（", "1", "）截至", "2021", "年", "12", "月"],
        ["31", "日、", "2022", "年", "12", "月", "31"],
        ["日、", "2023", "年", "12", "月", "31", "日、"],
        ["2024", "年", "12", "月", "31", "日和", "2025"],
        ["年", "12", "月", "31", "日，每股基本及摊薄盈利是按……", "", ""],
    ]


def test_year_sequence_assigns_columns_newest_first() -> None:
    """5 个数据列 + 脚注里 2021..2025 → 从新到旧分配。"""
    grid = _p7_capex_grid()
    out = periods_from_year_sequence(grid, data_cols={1, 2, 3, 4, 5})
    assert out == {1: "2025A", 2: "2024A", 3: "2023A", 4: "2022A", 5: "2021A"}, out


def test_year_sequence_skips_rows_containing_data_numbers() -> None:
    """★ 含数据数字的行不参与 —— 否则表头带来的年份会让整表偏移一年。

    实测踩过（p7 表 0）：它的数据区上方是从**别的表带来的期间表头**
    ``2025 年 | 2024 年 | 2023 年 …``，若连那行一起扫会得到 2021..2025，
    派成 ``2024A..2020A``，而真实期间是 ``2025A..2021A``。
    """
    grid = [
        ["项目", "2025", "年", "2024", "年", "2023", "年"],   # 表头行（含年份）
        ["营业收入", "2,864,469", "2,937,981", "3,012,812", ""],  # 数据行
    ]
    # 年份在"含数据数字的行"之外的那一行 —— 它其实是表头，规则**不应**据此分配，
    # 因为列头本来就有期间（调用方也不会在 col_period 非空时调用本函数）。
    # 这里断言的是：数据行里的数字不会被误当成年份。
    out = periods_from_year_sequence(
        grid, data_cols={1, 2, 3},
    )
    # 表头行 3 个年份 vs 3 个数据列 → 会命中；关键是它没把 2,864,469 当成年份
    assert set(out.values()) <= {"2023A", "2024A", "2025A"}, out


def test_year_sequence_refuses_on_count_mismatch() -> None:
    """年份个数 ≠ 数据列数 → 不猜。"""
    grid = [["资本性支出", "1", "2", "3", "4", "5", ""],
            ["注：（1）截至", "2021", "年", "2022", "年", "", ""]]
    # 只有 2 个年份 vs 5 个数据列
    assert periods_from_year_sequence(grid, data_cols={1, 2, 3, 4, 5}) == {}


def test_year_sequence_refuses_on_non_consecutive_years() -> None:
    """年份不连续 → 不是"多年摘要"的序列，不猜。"""
    grid = [["资本性支出", "1", "2", "3", ""],
            ["注：", "2019", "年", "2023", "年", "2025", "年"]]
    assert periods_from_year_sequence(grid, data_cols={1, 2, 3}) == {}


def test_year_sequence_refuses_on_duplicate_years() -> None:
    """同一年份出现两次 → 不是"一年一列"，不猜。"""
    grid = [["资本性支出", "1", "2", "3", ""],
            ["注：", "2025", "年", "2025", "年", "2025", "年"]]
    assert periods_from_year_sequence(grid, data_cols={1, 2, 3}) == {}


def test_year_sequence_refuses_without_enough_columns() -> None:
    """数据列少于 2 → 无歧义可言，不动。"""
    grid = [["资本性支出", "1"],
            ["注：", "2025", "年"]]
    assert periods_from_year_sequence(grid, data_cols={1}) == {}


def test_year_sequence_counts_distinct_years_not_occurrences() -> None:
    """★ 年份出现两次（表头 + 脚注）时，按**去重后**的个数判等。

    实测（601857 p7 五年摘要表，正是本规则要修的那张）：
    年份在整表里出现两次 —— 数据区上方的期间表头行
    ``2025 | 2024 | 2023 | 2022 | 2021``，以及脚注
    ``截至 2021 年 12 月 31 日、…… 2025 年 12 月 31 日``。

    共 10 个，而数据列只有 5 个。若按"原始出现次数"判等，
    判据 1 永远不成立 —— **规则在最需要它的那张表上失效**（实测踩过）。

    两处序列方向相反（表头从新到旧、脚注从旧到新）但集合相同，
    去重后恰好 5 个、连续、无重复。
    """
    grid = [
        ["资本性支出", "269,089", "275,849", "275,393", "274,494", "251,323"],
        ["经营活动产生的现金流量净额", "412,510", "406,532", "456,847",
         "393,246", "341,424"],
        ["", "2025", "2024", "2023", "2022", "2021"],          # 期间表头行
        ["注：（1）截至", "2021", "年", "12", "月", "31"],
        ["日、", "2022", "年", "12", "月", "31", "日、"],
        ["2023", "年", "12", "月", "31", "日、", "2024"],
        ["年", "12", "月", "31", "日和", "2025", "年"],
    ]
    out = periods_from_year_sequence(
        grid[:3],                       # 数据区（含期间表头行）
        data_cols={1, 2, 3, 4, 5},
        year_grid=grid,                 # 年份从整表取（脚注里有）
    )
    assert out == {1: "2025A", 2: "2024A", 3: "2023A", 4: "2022A", 5: "2021A"}, out